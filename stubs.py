"""
아직 비어있는 모듈/기능들의 자리표시자(placeholder) 페이지
=============================================================

"로드맵 전체를 겉 포장지부터 만든다"는 방향에 따라, 앞으로 채워나갈 모든
자산 모듈·공용 기능을 실제로 클릭해서 들어갈 수 있는 페이지로 미리
만들어둔다. 지금은 내용이 비어있지만, 앱의 전체 구조(내비게이션)는 처음부터
완성된 형태로 존재한다 — 나중에 각 함수의 본문만 채우면 된다.

각 페이지는 같은 틀(render_stub)을 재사용해서, 최소한 "이게 뭐가 될
예정인지"와 "왜 필요한지"는 보이도록 했다.
"""

from __future__ import annotations

import streamlit as st

STATUS_LABELS = {
    "idea": ("💡", "아이디어 단계", "아직 설계만 있고 구현은 시작 전이에요."),
    "progress": ("🔨", "제작 중", "일부는 다른 모듈 안에 이미 있고, 여기로 옮기거나 넓히는 작업이 남았어요."),
    "planned": ("📋", "다음 순서", "구조는 정해졌고, 다음으로 채워질 예정이에요."),
}


def render_stub(
    icon: str,
    title: str,
    status: str,
    tagline: str,
    what_it_will_do: list[str],
    why_it_matters: str,
    depends_on: str | None = None,
) -> None:
    """모든 placeholder 페이지가 공유하는 공통 틀."""
    status_icon, status_label, status_desc = STATUS_LABELS.get(status, STATUS_LABELS["idea"])

    st.title(f"{icon} {title}")
    st.caption(tagline)

    with st.container(border=True):
        c1, c2 = st.columns([1, 4])
        with c1:
            st.caption("상태")
            st.markdown(f"### {status_icon} {status_label}")
        with c2:
            st.write(status_desc)

    st.divider()

    st.markdown("#### 🧭 무엇이 채워질 예정인가")
    for item in what_it_will_do:
        st.markdown(f"- {item}")

    st.divider()

    st.markdown("#### 💡 왜 필요한가")
    st.write(why_it_matters)

    if depends_on:
        st.info(f"참고: {depends_on}")

    st.divider()
    st.caption("이 페이지는 아직 준비 중이에요 — 왼쪽 메뉴에서 '채권·금리'로 가면 지금 실제로 동작하는 부분을 볼 수 있어요.")


